"""Banco PostgreSQL para Escala Dragão.

A variável DATABASE_URL deve ser definida apenas no ambiente do Render.
Não existe fallback para SQLite: a indisponibilidade bloqueia as gravações.
"""
import os
import threading

import psycopg


class Database:
    def __init__(self, url):
        self.conn = psycopg.connect(
            url, autocommit=True, connect_timeout=12, sslmode="require"
        )
        # A conexão é compartilhada pelo cache do Streamlit: serializar as
        # transações evita que usuários simultâneos misturem operações.
        self.lock = threading.RLock()
        self.in_transaction = False

    def execute(self, sql, params=None):
        command = sql.strip().upper()
        if command in ("BEGIN", "BEGIN IMMEDIATE"):
            self.lock.acquire()
            try:
                result = self.conn.execute("BEGIN")
                self.in_transaction = True
                return result
            except Exception:
                self.lock.release()
                raise
        with self.lock:
            return self.conn.execute(sql.replace("?", "%s"), params or ())

    def commit(self):
        if self.in_transaction:
            try:
                self.conn.execute("COMMIT")
            finally:
                self.in_transaction = False
                self.lock.release()

    def rollback(self):
        if self.in_transaction:
            try:
                self.conn.execute("ROLLBACK")
            finally:
                self.in_transaction = False
                self.lock.release()

    def __enter__(self):
        self.execute("BEGIN")
        return self

    def __exit__(self, exc_type, exc, tb):
        if exc_type is None:
            self.commit()
        else:
            self.rollback()
        return False


def conectar_postgres():
    url = os.environ.get("DATABASE_URL", "").strip()
    if not url:
        raise RuntimeError("DATABASE_URL não configurada.")
    db = Database(url)
    db.execute("""CREATE TABLE IF NOT EXISTS militares
      (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ord INTEGER NOT NULL,
       nome TEXT NOT NULL, su TEXT NOT NULL, status TEXT NOT NULL,
       obs TEXT NOT NULL DEFAULT '', tipo TEXT NOT NULL DEFAULT 'AMBAS')""")
    db.execute("""CREATE TABLE IF NOT EXISTS escala
      (dia TEXT NOT NULL, militar_id BIGINT NOT NULL,
       valor TEXT NOT NULL, manual INTEGER NOT NULL DEFAULT 0,
       PRIMARY KEY(dia, militar_id))""")
    db.execute("""CREATE TABLE IF NOT EXISTS previsao_servico
      (dia TEXT NOT NULL, funcao TEXT NOT NULL, descricao TEXT NOT NULL DEFAULT '',
       PRIMARY KEY(dia, funcao))""")
    db.execute("""CREATE TABLE IF NOT EXISTS categoria_dia
      (dia TEXT PRIMARY KEY, tipo TEXT NOT NULL CHECK(tipo IN ('PRETA','VERMELHA')))""")
    return db
